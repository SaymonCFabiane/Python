import math
angulo = int(input('Digite um ângulo qualque: '))
seno = math.sin(angulo)
coseno = math.cos(angulo)
tangente = math.tan(angulo)
print(f'O ângulo é {angulo}, o seno é {seno:.2f}, o coseno é {coseno:.2f} e a tangente é {tangente:.2f}!')








